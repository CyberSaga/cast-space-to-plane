#: Scene blocks (the objects are inserted between ``up`` and ``lights``): version 0.1, metres, Z up; one
#: directional light ``sun`` from the viewer's upper left (:data:`~miki_model.rig.SUN_TOWARDS`); the receiver
#: ``ground`` (the plane z = 0); a portrait 3/4 front-left camera at about standing eye level; the output
#: layers ``objects`` and ``cast_shadow`` with hidden lines omitted (``examples/README.md`` describes the scene).
SCENE_SETTINGS = {
    "version": "0.1",
    "units": "m",
    "up": "z",
    "lights": [{"id": "sun", "type": "directional", "direction": None}],
    "receivers": [{"id": "ground", "type": "plane", "normal": [0, 0, 1], "offset": 0}],
    # r2 F13: 65 mm aimed a little right of her (target x 0.12) and lower (0.76): the figure fills ~75 % of the
    # frame height (was 57 % at 50 mm) and her ground shadow, which falls to the right, stays in the frame
    "camera": {"position": [1.7, -3.4, 1.25], "target": [0.12, 0.0, 0.76], "roll_deg": 0, "focal_length_mm": 65,
               "frame_mm": [24, 36], "shift_mm": [0.0, 0.0], "near_m": 0.05},
    "output": {"canvas_mm": [182, 273], "layers": ["objects", "cast_shadow"], "hidden_lines": True,
               "hidden_style": "omit", "png_dpi": 200},
}



def _sun_direction():
    v = np.asarray(SUN_TOWARDS, dtype=np.float64)
    v = v / math.sqrt(float(np.dot(v, v)))
    return [round(float(x), 12) + 0.0 for x in v]


def scene_dict(assembly, description: str = DESCRIPTION) -> dict:
    """The castplane scene as a dict (objects in the fixed order, inline data)."""
    s = json.loads(json.dumps(SCENE_SETTINGS))
    s["lights"][0]["direction"] = _sun_direction()
    out = {"description": description}
    for k in ("version", "units", "up"):
        out[k] = s[k]
    # each object: id, type, display_color (web 3D views only; the core ignores it), data
    out["objects"] = [{"id": o["id"], "type": o["type"], "display_color": display_color(o["id"]), "data": o["data"]}
                      for o in assembly.objects()]
    for k in ("lights", "receivers", "camera", "output"):
        out[k] = s[k]
    return out


def scene_text(assembly, description: str = DESCRIPTION) -> str:
    """Scene JSON text: indented structure, one compact line per ``data`` block, trailing newline."""
    scene = scene_dict(assembly, description)
    blobs = []
    for k, obj in enumerate(scene["objects"]):
        blobs.append(json.dumps(obj["data"], separators=(",", ":"), allow_nan=False))
        obj["data"] = f"@@DATA{k}@@"
    text = json.dumps(scene, indent=1, ensure_ascii=False, allow_nan=False)
    for k, blob in enumerate(blobs):
        text = text.replace(f'"@@DATA{k}@@"', blob, 1)
    return text + "\n"


def write_scene(assembly, path, description: str = DESCRIPTION) -> str:
    text = scene_text(assembly, description)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return text


def check_scene(text: str) -> dict:
    """Load the scene text with castplane (``castplane.load_scene``) and confirm that the written
    coordinates still give valid meshes: per object, no two vertices within 1e-5 m and no face with area
    <= 1e-10 m² after the JSON round trip.  Returns the validated castplane scene; raises on failure."""
    import castplane

    raw = json.loads(text)
    for obj in raw["objects"]:
        d = obj["data"]
        m = mk.Mesh(d["vertices"], d["faces"], d["smooth_groups"])
        rep = mk.validate(m, f"scene object {obj['id']}")
        if not rep.ok:
            raise mk.MeshError(rep.summary())
    return castplane.load_scene(raw)


