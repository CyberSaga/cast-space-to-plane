#: Scene blocks (the objects are inserted between ``up`` and ``lights``): version 0.1, metres, Z up; one
#: directional light ``sun`` from the viewer's upper left (:data:`~miki_model.rig.SUN_TOWARDS`); the receiver
#: ``ground`` (the plane z = 0); a portrait 3/4 front-left camera at about standing eye level; the output
#: layers ``objects`` and ``cast_shadow`` with hidden lines omitted (``examples/README.md`` describes the scene).
SCENE_SETTINGS = {
    "version": "0.1",
    "units": "m",
    "up": "z",
    "lights": [{"id": "sun", "type": "directional", "direction": None}],
    "receivers": [{"id": "ground", "type": "plane", "normal": [0, 0, 1], "offset": 0}],
    # r2 F13: 65 mm aimed a little right of her (target x 0.12) and lower (0.76): the figure fills ~75 % of the
    # frame height (was 57 % at 50 mm) and her ground shadow, which falls to the right, stays in the frame
    "camera": {"position": [1.7, -3.4, 1.25], "target": [0.12, 0.0, 0.76], "roll_deg": 0, "focal_length_mm": 65,
               "frame_mm": [24, 36], "shift_mm": [0.0, 0.0], "near_m": 0.05},
    "output": {"canvas_mm": [182, 273], "layers": ["objects", "cast_shadow"], "hidden_lines": True,
               "hidden_style": "omit", "png_dpi": 200},
}

#: Header lines of examples/meshes/miki.obj and miki.mtl.
OBJ_HEADER = ("# Hanabishi Miki drawing-reference model (castplane frame: Z up, metres, facing -Y)",
              "# generated by tools/make_miki_model.py",
              "# COPYRIGHT: " + NOTICE)
MTL_HEADER = ("# Miki model materials (tools/make_miki_model.py)",
              "# COPYRIGHT: " + NOTICE)

#: ``asset.generator`` and ``asset.copyright`` of examples/meshes/miki.glb.
GLB_GENERATOR = "tools/miki_model (castplane)"
GLB_COPYRIGHT = ("Hanabishi Miki (Hayate the Combat Butler) belongs to her rights holders; unofficial fan-made "
                 "reference, not part of this project's authorized distribution or dissemination "
                 "(COPYRIGHT_NOTICE.md)")


def scene_dict(assembly, description: str = DESCRIPTION) -> dict:
    """The castplane scene as a dict (objects in the fixed order, inline data)."""
    return _ex.scene_dict(CHARACTER, assembly, SCENE_SETTINGS, description)


def scene_text(assembly, description: str = DESCRIPTION) -> str:
    """Scene JSON text: indented structure, one compact line per ``data`` block, trailing newline."""
    return _ex.scene_text(CHARACTER, assembly, SCENE_SETTINGS, description)


def write_scene(assembly, path, description: str = DESCRIPTION) -> str:
    return _ex.write_scene(CHARACTER, assembly, path, SCENE_SETTINGS, description)


def mtl_text(assembly=None) -> str:
    """MTL text with every material of :data:`MATERIALS` (``Kd`` in sRGB, as most OBJ readers expect)."""
    return _ex.mtl_text(CHARACTER, MTL_HEADER)


def obj_text(assembly, mtl_name: str = "miki.mtl") -> str:
    """OBJ text: the objects in order (``o``), a ``usemtl`` per part block, global vertex numbering, ``s``
    ids unique across objects.  The vertex order is fixed with :func:`meshkit.fix_nesting` over the whole
    model, so a single-object import of the file (``castplane import miki.obj``) gets no orientation flip
    either."""
    return _ex.obj_text(assembly, mtl_name, OBJ_HEADER)


def write_obj(assembly, obj_path, mtl_path) -> None:
    _ex.write_obj(CHARACTER, assembly, obj_path, mtl_path, OBJ_HEADER, MTL_HEADER)


def glb_bytes(assembly, generator: str = GLB_GENERATOR) -> bytes:
    """The model as a binary glTF 2.0 file: one node / mesh per object, one primitive per material."""
    return _ex.glb_bytes(CHARACTER, assembly, generator, GLB_COPYRIGHT)


def write_glb(assembly, path) -> None:
    _ex.write_glb(CHARACTER, assembly, path, GLB_GENERATOR, GLB_COPYRIGHT)
