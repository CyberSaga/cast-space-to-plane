"""Writers of the Miki model: castplane scene JSON (inline mesh data), Wavefront OBJ + MTL, glTF 2.0 GLB.

The writers are character-free and live in :mod:`charmodel.export`; this module holds Miki's texts (the scene
:data:`SCENE_SETTINGS` and :data:`DESCRIPTION`, the OBJ / MTL header lines, the GLB generator and copyright
strings, all carrying the copyright :data:`NOTICE`) and thin wrappers with the public names the CLI and
``tests/test_miki_model.py`` use.  Every writer is deterministic (fixed object order, rounded coordinates, no
timestamps): running the generator twice gives byte-identical files.  Geometry comes from an
:class:`~charmodel.assembly.Assembly`: the castplane objects (:data:`~miki_model.assemble.OBJECTS`, spatially
compact groups of parts) and the material of every part (:data:`~miki_model.assemble.MATERIALS`).

* :func:`scene_text` / :func:`write_scene`: the scene of :data:`SCENE_SETTINGS` (a sun, the ground receiver, the
  3/4 front portrait camera) with one ``mesh`` object per castplane object and inline ``data``, each with
  ``display_color`` (lower-case ``"#rrggbb"`` of its dominant material,
  :func:`~miki_model.assemble.display_color`; read only by the web UI's 3D views, ignored by the core); the
  structure is indented, every ``data`` block is compact on one line.  :func:`check_scene` loads it with
  ``castplane.load_scene`` (lazy import).
* :func:`write_obj`: ``mtllib``, one ``o <object>`` per object and a ``usemtl <material>`` per part block
  (castplane's OBJ reader ignores ``usemtl``), ``s`` per smooth group (group ids made unique across objects;
  vertices ordered so that the whole file is also safe as a single castplane mesh).  The MTL has every
  material.
* :func:`write_glb`: one node + mesh per object (named by the object id) with one primitive per material
  (that material's faces, its own compact vertex set), POSITION / NORMAL (smoothed within a smooth group,
  vertices split at group boundaries) / indices; the materials array is :data:`MATERIALS` in order.
  castplane ``(x, y, z)`` is written as glTF ``(x, z, -y)`` (glTF is Y-up; castplane's importer maps back
  exactly and concatenates a mesh's primitives into one object).
"""

from __future__ import annotations

from charmodel import export as _ex
from charmodel.export import check_scene, srgb_to_linear

from .assemble import CHARACTER, OBJECTS

__all__ = ["SCENE_SETTINGS", "DESCRIPTION", "NOTICE", "OBJ_HEADER", "MTL_HEADER", "GLB_GENERATOR", "GLB_COPYRIGHT",
           "scene_dict", "scene_text", "write_scene", "check_scene", "obj_text", "mtl_text", "write_obj", "glb_bytes",
           "write_glb", "srgb_to_linear"]

