def srgb_to_linear(hex_colour: str):
    """``'#rrggbb'`` -> linear RGB floats (glTF ``baseColorFactor``), rounded to 6 decimals."""
    h = hex_colour.lstrip("#")
    out = []
    for k in range(3):
        c = int(h[2 * k:2 * k + 2], 16) / 255.0
        lin = c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
        out.append(round(lin, 6))
    return out


def _srgb(hex_colour: str):
    h = hex_colour.lstrip("#")
    return [round(int(h[2 * k:2 * k + 2], 16) / 255.0, 6) for k in range(3)]


def _fmt(x: float) -> str:
    return repr(float(x) + 0.0)


def mtl_text(assembly=None) -> str:
    """MTL text with every material of :data:`MATERIALS` (``Kd`` in sRGB, as most OBJ readers expect)."""
    lines = ["# Miki model materials (tools/make_miki_model.py)",
             "# COPYRIGHT: the character Hanabishi Miki (Hayate the Combat Butler) belongs to her rights holders; this model is an unofficial fan-made drawing reference, and the character is NOT part of this project's authorized distribution or dissemination (see COPYRIGHT_NOTICE.md)."]
    for name, colour in MATERIALS.items():
        r, g, b = _srgb(colour)
        lines += ["", f"newmtl {name}", f"Kd {r} {g} {b}", "Ka 0 0 0", "Ks 0 0 0", "d 1", "illum 1"]
    return "\n".join(lines) + "\n"


def obj_text(assembly, mtl_name: str = "miki.mtl") -> str:
    """OBJ text: the objects in order (``o``), a ``usemtl`` per part block, global vertex numbering, ``s``
    ids unique across objects.  The
    vertex order is fixed with :func:`meshkit.fix_nesting` over the whole model, so a single-object
    import of the file (``castplane import miki.obj``) gets no orientation flip either."""
    meshes = list(assembly.meshes.items())
    offset, pieces, spans = 0, [], []
    for oid, m in meshes:
        gmap = {g: g + offset for g in set(m.groups) if g}
        pieces.append(m.with_groups(gmap))
        spans.append((oid, m.n_faces))
        offset += max([0] + list(m.groups))
    whole = mk.fix_nesting(mk.merge(pieces), strict=False)   # best effort: buried shells stay as they are
    lines = ["# Hanabishi Miki drawing-reference model (castplane frame: Z up, metres, facing -Y)",
             "# generated by tools/make_miki_model.py",
             "# COPYRIGHT: the character Hanabishi Miki (Hayate the Combat Butler) belongs to her rights holders; this model is an unofficial fan-made drawing reference, and the character is NOT part of this project's authorized distribution or dissemination (see COPYRIGHT_NOTICE.md).", f"mtllib {mtl_name}"]
    lines += [f"v {_fmt(x)} {_fmt(y)} {_fmt(z)}" for x, y, z in whole.vertices]
    base = 0
    for oid, n in spans:
        lines.append(f"o {oid}")
        for part, mat, first, count in assembly.part_faces[oid]:
            lines += [f"# part {part}", f"usemtl {mat}"]
            current = None                          # restate the smooth group after each usemtl
            lo = base + first
            for f, g in zip(whole.faces[lo:lo + count], whole.groups[lo:lo + count]):
                if g != current:
                    lines.append(f"s {g}" if g else "s off")
                    current = g
                lines.append("f " + " ".join(str(i + 1) for i in f))
        base += n
    return "\n".join(lines) + "\n"


def write_obj(assembly, obj_path, mtl_path) -> None:
    import os

    with open(obj_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(obj_text(assembly, os.path.basename(mtl_path)))
    with open(mtl_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(mtl_text(assembly))


