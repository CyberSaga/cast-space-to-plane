    under = _concave_prism_scene([[-3, 1, 0], [3, 1, 0], [3, 7, 0], [-3, 7, 0]], [0, 4, 0], u_big, [0, 4.5, 0.5])
    for label, scene, area in (("beyond the arm", beyond, 15.0), ("under the prism", under, 31.375)):
        validated = castplane.load_scene(scene)
