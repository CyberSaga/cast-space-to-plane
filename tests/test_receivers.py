"""M4 bounded receivers, folds and per-receiver construction (contract §5.1.1–§5.1.5, §5.1.11; spec §9 / §10 M4).

The byte-identity gate of contract §5.1.2 / §5.1.8 / §5.1.11: with the new features switched off, the SVG of
every v2 conformance scene equals the v2 writer's output (``tests/golden/v2_svg_sha256.json``, generated by the
v2 code before M4) and the geometry JSON with the M4 keys stripped (``tools/regen_conformance.py
--strip-new-keys``) equals the committed v2 expected file.
"""

